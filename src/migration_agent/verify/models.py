"""Phase C shared data contracts (frozen: C-01..C-08 all code against these).

Files (all under the project folder):
  feedback/findings.json      FindingsFile    written by the Verifier (C-01/C-02/C-09)
  feedback/resolutions.json   ResolutionsFile written by the resolution engine (C-03)
  feedback/comments.json      CommentsFile    written by the comment system (C-05)
  feedback/decisions.json     DecisionsFile   per-quirk/bug migration decision (preserve|fix); absent => preserve
  feedback/approvals.json     ApprovalsFile   Phase 1 exit-gate approvals (history; the last one is current)
  docs/changelog.md           generated by C-08
  docs/understanding.vN.approved.md  immutable copy of the doc approved for graph vN
  docs/migration_contract.json       MigrationContract: what Phase 2 (migration) reads
"""
from __future__ import annotations

from typing import Literal

from pydantic import BaseModel, Field

FindingKind = Literal["contradiction", "doc_only", "code_only", "doc_vs_doc"]
Severity = Literal["low", "medium", "high"]
# "deferred": acknowledged but postponed to the migration phase (not a pending-reanalysis status)
ResolutionStatus = Literal["open", "accepted_doc", "accepted_code", "dismissed", "needs_reanalysis", "resolved",
                           "deferred"]
DecisionValue = Literal["preserve", "fix"]


class Quote(BaseModel):
    """A verbatim passage. `source` is "understanding" (the generated doc) or a user_docs file path."""
    source: str
    text: str
    anchor: str = ""          # section anchor in the converted markdown, if known
    verified: bool = False    # set by C-09 string check against the real text


class Finding(BaseModel):
    id: str                   # F-0001, stable within a findings file
    kind: FindingKind
    severity: Severity = "low"
    title: str
    detail: str = ""
    item_ids: list[str] = Field(default_factory=list)   # graph IDs (COMP-0001, RULE-0003 ...)
    quotes: list[Quote] = Field(default_factory=list)
    area: str = ""            # grouping key for code_only findings (module/directory)


class FindingsFile(BaseModel):
    schema_version: int = 1
    graph_version: int = 0
    findings: list[Finding] = Field(default_factory=list)
    dropped_unverifiable: int = 0     # C-09: findings dropped because a quote did not verify
    claims_extracted: int = 0


class Resolution(BaseModel):
    finding_id: str
    status: ResolutionStatus
    note: str = ""
    affected_node_ids: list[str] = Field(default_factory=list)
    created: str = ""                  # ISO timestamp


class ResolutionsFile(BaseModel):
    schema_version: int = 1
    resolutions: list[Resolution] = Field(default_factory=list)


class Comment(BaseModel):
    id: str                   # CM-0001
    item_id: str              # graph ID the comment attaches to
    text: str
    author: str = "user"
    created: str = ""
    processed: bool = False   # True once targeted re-analysis consumed it


class CommentsFile(BaseModel):
    schema_version: int = 1
    comments: list[Comment] = Field(default_factory=list)


class QuirkDecision(BaseModel):
    """Migration decision for one quirk / suspected-bug node. Absent decision => "preserve" (default)."""
    item_id: str
    decision: DecisionValue
    note: str = ""
    created: str = ""


class DecisionsFile(BaseModel):
    schema_version: int = 1
    decisions: list[QuirkDecision] = Field(default_factory=list)


class EffectiveDecision(BaseModel):
    """A decision as frozen into an approval / contract; `explicit` is False for the preserve default."""
    item_id: str
    name: str = ""
    quirk: bool = False
    suspected_bug: bool = False
    decision: DecisionValue
    note: str = ""
    explicit: bool = False


class Approval(BaseModel):
    graph_version: int
    graph_sha256: str          # sha256 of graph/snapshots/vNNN.json bytes
    doc_sha256: str            # sha256 of docs/understanding.latest.md text (utf-8) at approval time
    approved_by: str
    approved_at: str
    note: str = ""
    deferred_finding_ids: list[str] = Field(default_factory=list)
    decisions: list[EffectiveDecision] = Field(default_factory=list)
    open_questions: int = 0
    warnings: list[str] = Field(default_factory=list)
    approved_doc: str = ""     # project-relative path of the immutable approved copy


class ApprovalsFile(BaseModel):
    schema_version: int = 1
    approvals: list[Approval] = Field(default_factory=list)


class DeferredFinding(BaseModel):
    id: str
    kind: FindingKind
    title: str
    item_ids: list[str] = Field(default_factory=list)
    note: str = ""


class CoverageSummary(BaseModel):
    mapped: int = 0
    unmapped: int = 0
    excluded: int = 0
    complete: bool = False


class MigrationContract(BaseModel):
    """docs/migration_contract.json: the approved Phase 1 understanding that Phase 2 (migration) consumes.

    Single schema for writer (review/approval.approve) and reader (migrate/contract.py). Version history:
      1  initial
      2  adds `source_hash` (ingest_report.json source_hash at approval; "" if there was no ingest report)
    """
    schema_version: int = 2
    project_name: str
    project_source: str
    graph_version: int
    graph_sha256: str
    doc_sha256: str
    approved_by: str
    approved_at: str
    note: str = ""
    approved_doc: str          # project-relative, e.g. docs/understanding.v3.approved.md
    graph_snapshot: str        # project-relative, e.g. graph/snapshots/v003.json
    source_hash: str = ""      # ingest_report.json source_hash of the legacy source the approval is based on
    decisions: list[EffectiveDecision] = Field(default_factory=list)
    deferred_findings: list[DeferredFinding] = Field(default_factory=list)
    open_questions: list[str] = Field(default_factory=list)
    assumptions: list[str] = Field(default_factory=list)
    coverage: CoverageSummary = Field(default_factory=CoverageSummary)
    warnings: list[str] = Field(default_factory=list)
