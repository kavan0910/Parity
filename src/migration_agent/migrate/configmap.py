def render_md(cmap: ConfigMap) -> str:
    c = cmap.counts()
    out = ["# Config map", "", f"- Convention: `{cmap.convention}`",
           f"- Keys: {len(cmap.entries)} ({c['mapped']} mapped, {c['renamed']} renamed, {c['dropped']} dropped, "
           f"{c['open']} open)",
           f"- Secret scan of generated files: {'clean' if cmap.secret_scan.ok else 'FAILED'}", "",
           "| Source | Key | Secret | Status | Target key | Target file | Note |", "|---|---|---|---|---|---|---|"]

    def cell(s: str) -> str:
        return (s or "").replace("|", "\\|").replace("\n", " ")
    for e in cmap.entries:
        src = f"{e.source_file}:{e.line}" if e.line else e.source_file
        note = e.reason + (f" [{e.rule}]" if e.rule not in ("convention", "") else "")
        out.append(f"| {cell(src)} | `{cell(e.source_key)}` | {'yes' if e.is_secret else ''} | {e.status} | "
                   f"{('`' + cell(e.target_key) + '`') if e.target_key else ''} | {cell(e.target_file)} | {cell(note)} |")
    opened = [e for e in cmap.entries if e.status == "open"]
    if opened:
        out += ["", "## Open items (block cut-over)", ""]
        out += [f"- `{e.id}`: {e.reason} (decide with `migration-agent config set PROJECT '{e.id}' --status ...`)"
                for e in opened]
    if cmap.secrets:
        out += ["", "## Deploy-time secrets checklist", "",
                "Values are never read or copied by the agent. Provide each one in the target environment:", ""]
        out += [f"- [ ] `{s.env_name}` -> `{s.target_key}` (reference `{s.reference}`, vault `{s.vault}`)"
                for s in cmap.secrets]
    if cmap.generated_files:
        out += ["", "## Generated files", "", *[f"- `config/generated/{f}`" for f in cmap.generated_files]]
        if cmap.copied_to_target_code:
            out += ["", "Copied into target_code/ (not committed): "
                    + ", ".join(f"`{f}`" for f in cmap.copied_to_target_code)]
        if cmap.skipped_existing:
            out += ["", "Not copied (hand-written file exists, use --force): "
                    + ", ".join(f"`{f}`" for f in cmap.skipped_existing)]
    if not cmap.secret_scan.ok:
        out += ["", "## Secret scan findings", "",
                *[f"- {f['file']}:{f['line']} {f['kind']}" for f in cmap.secret_scan.findings]]
    return "\n".join(out) + "\n"


