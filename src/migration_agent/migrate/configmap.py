"""Config migration (docs/phase2-plan.md section 9, milestone M6): `config map` and `config set`.

Every `config` node of the approved graph and every key in facts/config.json (`extract/config.py`: file, key,
is_secret) is mapped to a key in the target's convention:

    spring   Spring Boot properties: same key (or the libmap rename), env-style keys via relaxed binding
             (DB_URL -> db.url); written to src/main/resources/application[-profile].(properties|yml), keeping
             the legacy file format for Spring sources
    django   settings read from the environment: UPPER_SNAKE names in settings_env.py + .env.example
    node     environment variables: .env.example + config/env.schema.json (JSON Schema for @fastify/env)
    go       environment struct: internal/config/config.go (caarlos0/env tags) + .env.example
    env      any other target: .env.example

with status `mapped | renamed | dropped (reason) | open`. Renames come from the deterministic libmap tables
(`knowledge/libmap/*.yaml`, kind `config_rename`, e.g. Spring Boot 2 -> 3 property renames); entries that need a
decision, ambiguous replacements and target-key collisions are `open`. CI files and compose wiring are `dropped`
(compose `environment:` entries map to env vars). `config set` records manual decisions (config/decisions.json),
which override the computed status.

Secrets (`is_secret`, a redacted preview, a secret-looking value or env name) map to REFERENCES only: `${NAME}` in
Spring files, a required env var without default elsewhere, plus a vault path placeholder in the deploy-time
checklist. Secret values are never read (code/ is already redacted) and never written. Non-secret values are copied
from the facts preview only when complete; otherwise the generated file references the env var.

Outputs: config/config_map.json (`ConfigMap`, no values at all), config/config_map.md, config/generated/<path>
(target-relative), copied into target_code/<path> when target_code/ exists (hand-written files without the
GENERATED marker are skipped unless --force). Nothing is committed: committing target_code/ belongs to codegen.
Every generated file is scanned with `ingest/secrets.py` first; a hit fails the command and nothing is generated.

    from migration_agent.migrate.configmap import build_config_map, config_gaps, set_decision
    cmap = build_config_map(project)            # ConfigMap (raises ConfigMapError on a secret-scan hit)
    config_gaps(project)                        # [] when cut-over may proceed; else open items / staleness
"""
from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Literal

import click
from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator

ConfigStatus = Literal["mapped", "renamed", "dropped", "open"]
Convention = Literal["spring", "django", "node", "go", "env"]
MARKER = "GENERATED by migration-agent config map"
_TARGET_KEY = re.compile(r"^[A-Za-z_][A-Za-z0-9_.\-\[\]]{0,199}$")
_CI_FILES = re.compile(r"(^|/)(\.github/|\.gitlab-ci\.ya?ml$|\.circleci/|azure-pipelines|bitbucket-pipelines|"
                       r"\.travis\.ya?ml$|\.drone\.ya?ml$|buildkite)", re.I)
_COMPOSE = re.compile(r"(^|/)(docker-)?compose[^/]*\.ya?ml$", re.I)
_SPRING_FILE = re.compile(r"(^|/)(application|bootstrap)(-([\w.-]+))?\.(properties|ya?ml)$", re.I)
_ENV_FILE = re.compile(r"(^|/)\.env(\.[\w.-]+)?$|\.env$", re.I)


class ConfigMapError(RuntimeError):
    pass


class _M(BaseModel):
    model_config = ConfigDict(extra="forbid")


class ConfigMapEntry(_M):
    id: str                              # "<file>:<key>"
    source_file: str
    source_key: str
    line: int | None = None
    node_id: str | None = None           # CFG-NNNN when the key is a graph node
    is_secret: bool = False
    status: ConfigStatus
    target_key: str = ""
    target_file: str = ""                # target-relative generated file ("" for dropped/open)
    env_name: str = ""                   # environment variable carrying the value at deploy time
    reference: str = ""                  # secrets: "${NAME}" (never a value)
    reason: str = ""                     # required for dropped / open
    rule: str = ""                       # "convention" | "libmap:<table>/<entry>" | "manual" | "drop:<rule>"
    decided_by: str = ""

    @model_validator(mode="after")
    def _check(self):
        if self.status in ("dropped", "open") and not self.reason:
            raise ValueError(f"{self.id}: status {self.status} needs a reason")
        if self.status in ("mapped", "renamed") and not self.target_key:
            raise ValueError(f"{self.id}: status {self.status} needs a target key")
        return self


class SecretRef(_M):
    env_name: str
    target_key: str
    reference: str
    vault: str
    sources: list[str] = Field(default_factory=list)


class ScanResult(_M):
    ok: bool = True
    findings: list[dict] = Field(default_factory=list)     # {file, line, kind}: never the value


class ConfigMap(_M):
    """config/config_map.json. Holds keys and decisions only, never values."""
    schema_version: Literal[1] = 1
    created: str = ""
    convention: Convention
    target_sha256: str = ""
    facts_sha256: str = ""
    entries: list[ConfigMapEntry] = Field(default_factory=list)
    generated_files: list[str] = Field(default_factory=list)
    copied_to_target_code: list[str] = Field(default_factory=list)
    skipped_existing: list[str] = Field(default_factory=list)
    secrets: list[SecretRef] = Field(default_factory=list)
    secret_scan: ScanResult = Field(default_factory=ScanResult)

    def counts(self) -> dict[str, int]:
        out = {s: 0 for s in ("mapped", "renamed", "dropped", "open")}
        for e in self.entries:
            out[e.status] += 1
        return out


class ConfigDecision(_M):
    id: str
    status: ConfigStatus
    target_key: str = ""
    reason: str = ""
    by: str = "human"
    at: str = ""

    @field_validator("target_key")
    @classmethod
    def _tk(cls, v):
        if v and not _TARGET_KEY.match(v):
            raise ValueError(f"invalid target key {v!r}")
        return v

    @model_validator(mode="after")
    def _check(self):
        if self.status in ("dropped", "open") and not self.reason.strip():
            raise ValueError(f"status {self.status} needs --reason")
        if self.status in ("mapped", "renamed") and not self.target_key:
            raise ValueError(f"status {self.status} needs --target-key")
        return self


class ConfigDecisions(_M):
    schema_version: Literal[1] = 1
    decisions: dict[str, ConfigDecision] = Field(default_factory=dict)


