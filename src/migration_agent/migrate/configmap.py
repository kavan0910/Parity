def _scan(files: dict[str, str]) -> ScanResult:
    from ..ingest.secrets import redact_text
    findings = []
    for rel, text in sorted(files.items()):
        findings += [{"file": rel, "line": f.line, "kind": f.kind} for f in redact_text(rel, text)[1]]
    return ScanResult(ok=not findings, findings=findings)


def _audit(project, action: str, **fields) -> None:
    from ..audit import AuditLog
    try:
        AuditLog(Path(project.root) / "audit" / "audit.jsonl").record("configmap", action, **fields)
    except OSError:
        pass


def build_config_map(project, *, force: bool = False) -> ConfigMap:
    """Compute the map, render + scan generated files, write config/ outputs, copy into target_code/."""
    import shutil
    from .state import atomic_write_json, atomic_write_text, now_iso, sha256_file
    from .target import TargetSpecError, load_target
    lay = _layout(project)
    try:
        target = load_target(project)
    except TargetSpecError as e:
        raise ConfigMapError(str(e)) from None
    items, facts_sha = _items(project)
    conv = convention_for(target)
    entries = compute_entries(project, target, items)
    values = {it["file"] + ":" + it["key"]: _usable_value(it["value"]) for it in items}
    for e in entries:
        if e.is_secret:
            values[e.id] = None
    slug = re.sub(r"[^a-z0-9-]+", "-", Path(project.root).name.lower()).strip("-") or "service"
    vault = f"vault:secret/data/{slug}"
    files = render_files(conv, entries, values, vault)
    secrets: dict[str, SecretRef] = {}
    for e in entries:
        if e.is_secret and e.status in ("mapped", "renamed"):
            s = secrets.setdefault(e.env_name, SecretRef(env_name=e.env_name, target_key=e.target_key,
                                                         reference=e.reference, vault=f"{vault}/{e.env_name}"))
            s.sources.append(e.id)
    cmap = ConfigMap(created=now_iso(), convention=conv, target_sha256=sha256_file(lay.target_yaml),
                     facts_sha256=facts_sha, entries=entries, secrets=list(secrets.values()))
    cmap.secret_scan = _scan({**files, "config_map.md": render_md(cmap),
                              "config_map.json": cmap.model_dump_json(indent=2)})
    lay.ensure(lay.config_dir)
    if not cmap.secret_scan.ok:
        atomic_write_json(lay.config_map_json, cmap)
        atomic_write_text(lay.config_map_md, render_md(cmap))
        _audit(project, "config_map_secret_hit", findings=cmap.secret_scan.findings)
        raise ConfigMapError("secret scan of generated config failed: " + ", ".join(
            f"{f['file']}:{f['line']} {f['kind']}" for f in cmap.secret_scan.findings) + " (nothing generated)")
    gen = generated_dir(project)
    if gen.exists():
        shutil.rmtree(gen)
    for rel, text in sorted(files.items()):
        atomic_write_text(gen / rel, text)
    cmap.generated_files = sorted(files)
    if lay.target_code.is_dir():
        root = lay.target_code.resolve()
        for rel in cmap.generated_files:
            dst = (lay.target_code / rel).resolve()
            if not dst.is_relative_to(root) or (dst.exists() and dst.is_symlink()):
                cmap.skipped_existing.append(rel)
                continue
            if dst.exists() and MARKER not in dst.read_text(errors="replace") and not force:
                cmap.skipped_existing.append(rel)
                continue
            atomic_write_text(dst, files[rel])
            cmap.copied_to_target_code.append(rel)
    atomic_write_json(lay.config_map_json, cmap)
    atomic_write_text(lay.config_map_md, render_md(cmap))
    _audit(project, "config_map", convention=conv, counts=cmap.counts(), generated=cmap.generated_files,
           copied=cmap.copied_to_target_code, skipped=cmap.skipped_existing)
    return cmap


def load_config_map(project) -> ConfigMap | None:
    p = _layout(project).config_map_json
    return ConfigMap.model_validate_json(p.read_text()) if p.exists() else None


def resolve_entry_id(project, key: str) -> str:
    """KEY or FILE:KEY -> entry id; ambiguity is an error."""
    items, _ = _items(project)
    ids = {f"{i['file']}:{i['key']}" for i in items}
    if key in ids:
        return key
    hits = sorted(f"{i['file']}:{i['key']}" for i in items if i["key"] == key)
    if len(hits) == 1:
        return hits[0]
    if hits:
        raise ConfigMapError(f"{key!r} is in several files; use FILE:KEY, one of: {', '.join(hits)}")
    raise ConfigMapError(f"unknown config key {key!r} (not in facts/config.json or the approved graph)")


def set_decision(project, key: str, *, status: str, target_key: str = "", reason: str = "",
                 by: str = "human") -> ConfigDecision:
    from pydantic import ValidationError
    from .state import atomic_write_json, file_lock, now_iso
    eid = resolve_entry_id(project, key)
    try:
        d = ConfigDecision(id=eid, status=status, target_key=target_key, reason=reason, by=by, at=now_iso())
    except ValidationError as e:
        raise ConfigMapError("; ".join(x["msg"] for x in e.errors())) from None
    p = decisions_path(project)
    _layout(project).ensure(_layout(project).config_dir)
    with file_lock(p):
        ds = load_decisions(project)
        ds.decisions[eid] = d
        atomic_write_json(p, ds)
    _audit(project, "config_decision", id=eid, status=status, target_key=target_key, by=by)
    return d


def config_gaps(project) -> list[dict]:
    """Cut-over gate: open config items (plus a missing, stale or secret-failing map). [] means no gaps."""
    from .state import sha256_file
    lay = _layout(project)
    cmap = load_config_map(project)
    if cmap is None:
        return [{"id": "", "reason": "config map not generated: run `migration-agent config map PROJECT`"}]
    gaps: list[dict] = []
    if not cmap.secret_scan.ok:
        gaps.append({"id": "", "reason": "secret scan of generated config failed"})
    facts = Path(project.facts) / "config.json"
    if facts.exists() and cmap.facts_sha256 and sha256_file(facts) != cmap.facts_sha256:
        gaps.append({"id": "", "reason": "config map is stale (facts/config.json changed): re-run `config map`"})
    if lay.target_yaml.exists() and cmap.target_sha256 and sha256_file(lay.target_yaml) != cmap.target_sha256:
        gaps.append({"id": "", "reason": "config map is stale (target/target.yaml changed): re-run `config map`"})
    gaps += [{"id": e.id, "reason": e.reason} for e in cmap.entries if e.status == "open"]
    return gaps


# ------------------------------------------------------------------ CLI
def register(groups) -> None:
    def _project(path: Path):
        from ..project import Project
        try:
            return Project.load(path)
        except (FileNotFoundError, ValueError) as e:
            raise click.ClickException(str(e))

    def _gate(p):
        from .contract import ContractError, require_contract
        try:
            require_contract(p)
        except ContractError as e:
            raise click.ClickException(f"contract gate: {e}")

    @groups.config.command("map")
    @click.argument("project", type=click.Path(exists=True, path_type=Path))
    @click.option("--format", "fmt", type=click.Choice(["md", "json"]), default="md", show_default=True)
    @click.option("--force", is_flag=True, help="Overwrite hand-written config files in target_code/.")
    def map_cmd(project: Path, fmt: str, force: bool) -> None:
        """Map every legacy config key to the target convention (secrets as references only)."""
        p = _project(project)
        _gate(p)
        try:
            cmap = build_config_map(p, force=force)
        except ConfigMapError as e:
            raise click.ClickException(str(e))
        click.echo(cmap.model_dump_json(indent=2) if fmt == "json" else render_md(cmap), nl=False)
        if fmt == "md":
            c = cmap.counts()
            click.echo(f"\nwritten: config/config_map.json, config/config_map.md, {len(cmap.generated_files)} file(s) "
                       f"in config/generated/ ({c['open']} open)", err=True)

    @groups.config.command("set")
    @click.argument("project", type=click.Path(exists=True, path_type=Path))
    @click.argument("key")
    @click.option("--status", type=click.Choice(["mapped", "renamed", "dropped", "open"]), required=True)
    @click.option("--target-key", default="", help="Target key (required for mapped/renamed).")
    @click.option("--reason", default="", help="Why (required for dropped/open).")
    @click.option("--by", default="human", show_default=True)
    def set_cmd(project: Path, key: str, status: str, target_key: str, reason: str, by: str) -> None:
        """Record a manual decision for one config key (KEY or FILE:KEY), then re-map."""
        p = _project(project)
        _gate(p)
        try:
            d = set_decision(p, key, status=status, target_key=target_key, reason=reason, by=by)
        except ConfigMapError as e:
            raise click.ClickException(str(e))
        click.echo(f"{d.id}: {d.status}" + (f" -> {d.target_key}" if d.target_key else ""))
        try:
            cmap = build_config_map(p)
            click.echo(f"config map updated: {cmap.counts()['open']} open")
        except ConfigMapError as e:
            click.echo(f"decision saved; re-mapping failed: {e}", err=True)
