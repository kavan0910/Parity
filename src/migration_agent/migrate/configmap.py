def convention_for(target) -> Convention:
    from .knowledge import norm_language, split_framework
    raw = (target.target.language or "").lower()
    lang = norm_language(raw)
    fw = split_framework(target.target.framework or "")[0]
    if fw.startswith("spring") or raw in ("java", "kotlin"):
        return "spring"
    if lang == "python":
        return "django" if fw == "django" else "env"
    if lang == "javascript":
        return "node"
    if lang == "go":
        return "go"
    return "env"


def env_name(key: str) -> str:
    n = re.sub(r"\[(\d+)\]", r"_\1", key)
    n = re.sub(r"[^A-Za-z0-9]+", "_", n).strip("_").upper()
    if not n:
        return "_"
    return "_" + n if n[0].isdigit() else n


def _spring_key(key: str) -> str:
    if re.fullmatch(r"[A-Z0-9_]+", key):          # env style: relaxed binding DB_URL -> db.url
        return key.lower().replace("_", ".")
    return key


def _is_secret(item: dict) -> bool:
    from ..ingest.secrets import redact_text
    from .exec.policy import SECRET_NAME
    if item["is_secret"]:
        return True
    v = item.get("value")
    if v and ("<redacted>" in v or "[REDACTED" in v):
        return True
    if v and (redact_text("", f"{item['key']}={v}")[1] or redact_text("", v)[1]):
        return True
    return bool(SECRET_NAME.search(env_name(item["key"])))


def _usable_value(v: str | None) -> str | None:
    if v is None or v in ("<dict>", "<list>") or "[REDACTED" in v or "<redacted>" in v:
        return None
    from ..extract.config import PREVIEW_MAX
    if len(v) > PREVIEW_MAX and v.endswith("..."):
        return None            # truncated preview
    return v


def _regex_literal(rx: str) -> tuple[str, str] | None:
    """`^server\\.max-http-header-size$` -> ("server.max-http-header-size", "exact"); `^spring\\.redis\\.` ->
    ("spring.redis.", "prefix"); anything with other regex syntax -> None."""
    body = rx[1:] if rx.startswith("^") else None
    if body is None:
        return None
    kind = "prefix"
    if body.endswith("$"):
        body, kind = body[:-1], "exact"
    lit = re.sub(r"\\([.\-_/])", r"\1", body)
    if re.search(r"[\\()\[\]|*+?{}^$]", lit):
        return None
    if kind == "prefix" and not lit.endswith("."):
        return None
    return lit, kind


def libmap_rename(entry, key: str) -> tuple[str, str, str]:
    """(status, target_key, reason) for a config key matched by a libmap `config_rename` entry."""
    rep = entry.replacement.strip()
    why = f"{entry.title} ({entry.note})"
    if re.match(r"^(none|remove|delete|drop)\b", rep, re.I):
        if entry.needs_decision:
            return "open", "", f"{why}; suggested: {rep}; needs a decision"
        return "dropped", "", f"{entry.title}: {rep}"
    first = re.split(r"[,\s]", rep, maxsplit=1)[0]
    target = ""
    if re.fullmatch(r"[A-Za-z0-9_.\-<>*]+", first) and ("." in first or first.isupper()):
        for rx in entry.match.config_keys:
            if not re.search(rx, key):
                continue
            lit = _regex_literal(rx)
            if lit is None:
                break
            src, kind = lit
            if kind == "exact" and key == src and not re.search(r"[*<]", first):
                target = first
            elif kind == "prefix" and key.startswith(src) and first.endswith(".*"):
                rest = key[len(src):]
                new = first[:-1]
                for ph in re.findall(r"<[^>]+>", new):
                    seg, _, rest = rest.partition(".")
                    if not seg:
                        new = ""
                        break
                    new = new.replace(ph, seg, 1)
                target = (new + rest).rstrip(".") if new else ""
            break
    if not target:
        return "open", "", f"{why}; replacement needs a manual decision: {rep}"
    if entry.needs_decision:
        return "open", target, f"{why}; suggested target {target}, needs a decision"
    return "renamed", target, why


def _items(project) -> tuple[list[dict], str]:
    """Union of graph `config` nodes (approved snapshot) and facts/config.json keys."""
    from ..extract.config import ConfigFacts, make_key
    from .state import sha256_file
    facts_file = Path(project.facts) / "config.json"
    items: dict[tuple[str, str], dict] = {}
    facts_sha = ""
    if facts_file.exists():
        facts_sha = sha256_file(facts_file)
        facts = ConfigFacts.model_validate_json(facts_file.read_text())
        for k in facts.keys:
            items.setdefault((k.file, k.key), {"file": k.file, "key": k.key, "line": k.line,
                                               "is_secret": k.is_secret, "value": k.value_preview,
                                               "node_id": None})
    try:
        from .harness import HarnessError, approved_graph
        graph = approved_graph(project)
    except HarnessError:
        graph = None
    for n in (graph.nodes if graph is not None else []):
        if n.type != "config":
            continue
        key = (n.module, n.name)
        if key in items:
            items[key]["node_id"] = n.id
        else:
            line = n.evidence[0].line_start if n.evidence else None
            items[key] = {"file": n.module, "key": n.name, "line": line,
                          "is_secret": make_key(n.module or "?", line or 1, n.name, None).is_secret,
                          "value": None, "node_id": n.id}
    return sorted(items.values(), key=lambda i: (i["file"], i["line"] or 0, i["key"])), facts_sha


def _yaml_top_keys(project, rel: str) -> set[str]:
    p = Path(project.code) / rel
    try:
        import yaml
        d = yaml.safe_load(p.read_text(errors="replace")) if p.is_file() and p.stat().st_size < 1_000_000 else None
    except Exception:  # noqa: BLE001 - only a classification hint
        return set()
    return set(d) if isinstance(d, dict) else set()


def _target_file(conv: Convention, src_file: str, target) -> str:
    if conv == "spring":
        m = _SPRING_FILE.search(src_file)
        if m:
            prof = m.group(4)
            ext = "properties" if m.group(5).lower() == "properties" else "yml"
            return f"src/main/resources/application{'-' + prof if prof else ''}.{ext}"
        return "src/main/resources/application.yml"
    if conv == "django":
        root = (target.style.package_root or "").strip("/").replace(".", "/")
        return f"{root + '/' if root else ''}settings_env.py"
    if conv == "go":
        return "internal/config/config.go"
    if conv == "node":
        return "config/env.schema.json"
    return ".env.example"


def load_decisions(project) -> ConfigDecisions:
    p = decisions_path(project)
    if not p.exists():
        return ConfigDecisions()
    return ConfigDecisions.model_validate_json(p.read_text())


def compute_entries(project, target, items: list[dict]) -> list[ConfigMapEntry]:
    from .knowledge import libmaps_for
    conv = convention_for(target)
    renames = [(m, e) for m in libmaps_for(target) for e in m.entries
               if e.kind == "config_rename" and e.match.config_keys]
    decisions = load_decisions(project).decisions
    k8s_cache: dict[str, bool] = {}
    out: list[ConfigMapEntry] = []
    for it in items:
        f, key = it["file"], it["key"]
        eid = f"{f}:{key}"
        secret = _is_secret(it)
        base_key = key
        status, tkey, reason, rule = "mapped", "", "", "convention"
        if _CI_FILES.search(f):
            status, reason, rule = "dropped", f"CI pipeline file {f}: not service configuration", "drop:ci"
        elif _COMPOSE.search(f):
            m = re.search(r"\.environment\.([^.]+)$", key)
            if m:
                base_key = m.group(1)
            else:
                status, reason, rule = ("dropped", f"container wiring in {f}: re-create it in the target deployment "
                                        "(the sandbox uses harness/harness.yaml)", "drop:compose")
        elif f.lower().endswith((".yml", ".yaml")) and not _SPRING_FILE.search(f):
            if f not in k8s_cache:
                k8s_cache[f] = {"apiVersion", "kind"} <= _yaml_top_keys(project, f)
            if k8s_cache[f]:
                status, reason, rule = "open", f"deployment manifest {f}: decide how the target deploys it", "k8s"
        if status == "mapped":
            for m, e in renames:
                if any(re.search(rx, base_key) for rx in e.match.config_keys):
                    status, renamed, reason = libmap_rename(e, base_key)
                    rule = f"libmap:{m.id}/{e.id}"
                    base_key = renamed or base_key
                    break
        if status in ("mapped", "renamed", "open") and not (status == "open" and rule == "k8s"):
            tkey = _spring_key(base_key) if conv == "spring" else env_name(base_key)
            if conv == "spring" and status == "mapped" and tkey != key and not _COMPOSE.search(f):
                reason = f"relaxed binding of {key}"
        env = env_name(tkey) if conv == "spring" and tkey else (tkey or env_name(base_key))
        out.append({"id": eid, "source_file": f, "source_key": key, "line": it["line"], "node_id": it["node_id"],
                    "is_secret": secret, "status": status, "target_key": tkey, "env_name": env,
                    "reason": reason, "rule": rule, "decided_by": "", "_base": base_key})
    # target-key collisions: the first source keeps the key, later ones become open
    seen: dict[tuple[str, str], tuple[str, str]] = {}
    for e in out:
        if e["status"] not in ("mapped", "renamed"):
            continue
        tf = _target_file(conv, e["source_file"], target)
        k = (tf, e["target_key"])
        if k in seen and seen[k][1] != e["_base"]:
            e["status"], e["reason"] = "open", f"target key {e['target_key']} collides with {seen[k][0]}"
        else:
            seen.setdefault(k, (e["id"], e["_base"]))
    entries = []
    for e in out:
        e.pop("_base", None)
        d = decisions.get(e["id"])
        if d is not None:
            e.update(status=d.status, target_key=d.target_key or e["target_key"], reason=d.reason, rule="manual",
                     decided_by=d.by)
            if d.target_key:
                e["env_name"] = env_name(d.target_key)
        if e["status"] in ("mapped", "renamed"):
            e["target_file"] = _target_file(conv, e["source_file"], target)
        if e["is_secret"] and e["status"] in ("mapped", "renamed"):
            e["reference"] = "${" + e["env_name"] + "}"
        entries.append(ConfigMapEntry.model_validate(e))
    return entries


# ------------------------------------------------------------------ rendering generated files
def _scalar(v: str):
    import yaml
    try:
        x = yaml.safe_load(v)
    except yaml.YAMLError:
        return v
    return x if isinstance(x, (int, float, bool)) and not isinstance(x, type(None)) else v


def _props_escape(s: str, key: bool = False) -> str:
    s = s.replace("\\", "\\\\").replace("\n", "\\n")
    if key:
        s = re.sub(r"([=: ])", r"\\\1", s)
    elif s.startswith(" "):
        s = "\\" + s
    return "".join(c if ord(c) < 128 else f"\\u{ord(c):04x}" for c in s)


def _env_value(v: str) -> str:
    if re.fullmatch(r"[A-Za-z0-9_./:@+,=-]*", v):
        return v
    return '"' + v.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _go_field(name: str, used: set[str]) -> str:
    f = "".join(p.capitalize() for p in name.lower().split("_") if p) or "X"
    if f[0].isdigit():
        f = "X" + f
    base, i = f, 2
    while f in used:
        f, i = f"{base}{i}", i + 1
    used.add(f)
    return f


def render_files(conv: Convention, entries: list[ConfigMapEntry], values: dict[str, str | None],
                 vault_prefix: str) -> dict[str, str]:
    """target-relative path -> file text. `values`: entry id -> usable non-secret value (None = unknown)."""
    import yaml
    live = [e for e in entries if e.status in ("mapped", "renamed")]
    head = f"{MARKER} from config/config_map.json (do not put secret values here; they are deploy-time env vars)"
    files: dict[str, str] = {}
    env_lines: dict[str, str] = {}

    def env_line(e: ConfigMapEntry) -> None:
        if e.env_name in env_lines:
            return
        v = None if e.is_secret else values.get(e.id)
        if e.is_secret:
            env_lines[e.env_name] = f"# secret ({vault_prefix}/{e.env_name}): supplied at deploy time\n{e.env_name}="
        elif v is None:
            env_lines[e.env_name] = f"# value not known from the legacy config: set at deploy time\n{e.env_name}="
        else:
            env_lines[e.env_name] = f"{e.env_name}={_env_value(v)}"

    if conv == "spring":
        by_file: dict[str, list[ConfigMapEntry]] = {}
        for e in live:
            by_file.setdefault(e.target_file, []).append(e)
        for tf, es in sorted(by_file.items()):
            pairs = []
            for e in es:
                v = values.get(e.id)
                if e.is_secret or v is None:
                    val = "${" + e.env_name + "}"
                else:
                    val = v
                pairs.append((e.target_key, val, e.is_secret))
            if tf.endswith(".properties"):
                lines = [f"# {head}"]
                for k, v, sec in pairs:
                    if sec:
                        lines.append(f"# secret reference: supplied at deploy time ({vault_prefix}/{env_name(k)})")
                    lines.append(f"{_props_escape(k, key=True)}={_props_escape(str(v))}")
                files[tf] = "\n".join(lines) + "\n"
            else:
                tree: dict = {}
                for k, v, _ in pairs:
                    val = v if str(v).startswith("${") else _scalar(str(v))
                    node, parts = tree, k.split(".")
                    ok = True
                    for p in parts[:-1]:
                        nxt = node.setdefault(p, {})
                        if not isinstance(nxt, dict):
                            ok = False
                            break
                        node = nxt
                    if ok and not isinstance(node.get(parts[-1]), dict):
                        node[parts[-1]] = val
                    else:
                        tree[k] = val            # leaf/prefix conflict: flat key (Spring flattens YAML)
                files[tf] = f"# {head}\n" + yaml.safe_dump(tree, sort_keys=False, default_flow_style=False)
        return files
    for e in live:
        env_line(e)
    env_text = f"# {head}\n" + "\n".join(env_lines[k] for k in sorted(env_lines)) + "\n"
    files[".env.example"] = env_text
    if conv == "django":
        tf = live[0].target_file if live else "settings_env.py"
        lines = [f'"""{head}.', "", "Import from settings.py: `from .settings_env import *` (secrets have no default).", '"""',
                 "import os", ""]
        done = set()
        for e in sorted(live, key=lambda e: e.env_name):
            if e.env_name in done or not e.env_name.isidentifier():
                continue
            done.add(e.env_name)
            v = None if e.is_secret else values.get(e.id)
            if e.is_secret:
                lines.append(f'{e.env_name} = os.environ["{e.env_name}"]  # secret: supplied at deploy time')
            elif v is None:
                lines.append(f'{e.env_name} = os.environ.get("{e.env_name}")')
            else:
                lines.append(f'{e.env_name} = os.environ.get("{e.env_name}", {json.dumps(v)})')
        files[tf] = "\n".join(lines) + "\n"
    elif conv == "node":
        props, required = {}, []
        for e in sorted(live, key=lambda e: e.env_name):
            if e.env_name in props:
                continue
            v = None if e.is_secret else values.get(e.id)
            props[e.env_name] = {"type": "string", **({"default": v} if v is not None else {})}
            if v is None:
                required.append(e.env_name)
        files["config/env.schema.json"] = json.dumps(
            {"$comment": head, "type": "object", "required": required, "properties": props}, indent=2) + "\n"
    elif conv == "go":
        used: set[str] = set()
        lines = [f"// Code {MARKER}. DO NOT EDIT.", "", "package config", "",
                 "// Config is loaded from the environment (github.com/caarlos0/env tags); secrets have no default.",
                 "type Config struct {"]
        done = set()
        for e in sorted(live, key=lambda e: e.env_name):
            if e.env_name in done:
                continue
            done.add(e.env_name)
            v = None if e.is_secret else values.get(e.id)
            tag = f'env:"{e.env_name}' + (',required"' if v is None else '"')
            if v is not None and re.fullmatch(r'[^`"\n\\]*', v):
                tag += f' envDefault:"{v}"'
            elif v is not None:
                tag = f'env:"{e.env_name},required"'
            note = "  // secret: supplied at deploy time" if e.is_secret else ""
            lines.append(f"\t{_go_field(e.env_name, used)} string `{tag}`{note}")
        lines.append("}")
        files["internal/config/config.go"] = "\n".join(lines) + "\n"
    return files


