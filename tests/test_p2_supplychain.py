LOCK_V3 = json.dumps({"lockfileVersion": 3, "packages": {
    "": {"name": "app"}, "node_modules/express": {"version": "4.19.2"},
    "node_modules/@scope/pkg": {"version": "1.0.0"}, "node_modules/express/node_modules/qs": {"version": "6.11.0"}}})


def test_parsers():
    assert {(c["name"], c["version"]) for c in sc.parse_package_lock(LOCK_V3)} == {
        ("express", "4.19.2"), ("@scope/pkg", "1.0.0"), ("qs", "6.11.0")}
    v1 = json.dumps({"dependencies": {"a": {"version": "1.0.0", "dependencies": {"b": {"version": "2.0.0"}}}}})
    assert {c["name"] for c in sc.parse_package_lock(v1)} == {"a", "b"}
    got, unp = sc.parse_requirements("flask==3.0.2\nrequests>=2\n# c\n-r other.txt\nDjango[argon2]==5.0.1 # x\n")
    assert [(c["name"], c["version"]) for c in got] == [("flask", "3.0.2"), ("Django", "5.0.1")] and unp == ["requests"]
    assert sc.parse_toml_packages('[[package]]\nname = "x"\nversion = "1.2"\n', "pypi")[0]["name"] == "x"
    assert [c["version"] for c in sc.parse_go_sum("a.b/c v1.0.0 h1:x\na.b/c v1.0.0/go.mod h1:y\n")] == ["v1.0.0"]
    assert sc.parse_gradle_lockfile("# c\norg.x:lib:1.2.3=compileClasspath\n")[0] == {
        "ecosystem": "maven", "name": "org.x:lib", "version": "1.2.3"}
    pom = ("<project xmlns='http://maven.apache.org/POM/4.0.0'><dependencies><dependency><groupId>g</groupId>"
           "<artifactId>a</artifactId><version>1.0</version></dependency><dependency><groupId>g</groupId>"
           "<artifactId>b</artifactId><version>${v}</version></dependency></dependencies></project>")
    got, unp = sc.parse_pom(pom)
    assert [c["name"] for c in got] == ["g:a"] and unp == ["g:b"]
    yarn = 'lodash@^4.17.0:\n  version "4.17.21"\n  resolved "x"\n\n"@a/b@^1.0.0":\n  version "1.0.1"\n'
    assert {(c["name"], c["version"]) for c in sc.parse_yarn_lock(yarn)} == {("lodash", "4.17.21"), ("@a/b", "1.0.1")}


def test_purl_and_cyclonedx():
    assert sc.purl({"ecosystem": "npm", "name": "@s/p", "version": "1"}) == "pkg:npm/%40s/p@1"
    assert sc.purl({"ecosystem": "maven", "name": "g:a", "version": "1"}) == "pkg:maven/g/a@1"
    bom = sc.cyclonedx([{"ecosystem": "pypi", "name": "x", "version": "1"}] * 2, name="svc")
    assert bom["bomFormat"] == "CycloneDX" and bom["specVersion"] == "1.5" and len(bom["components"]) == 1


def _tree(root: Path, files: dict):
    for rel, text in files.items():
        p = root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)


def test_scan_hashes_flags_generated_lockfile_and_unlocked_manifest(tmp_path):
    src, ws = tmp_path / "src", tmp_path / "ws"
    _tree(src, {"package.json": "{}", "go/go.mod": "module x\n", "py/requirements.txt": "flask==3.0.2\nrequests\n"})
    _tree(ws, {"package.json": "{}", "package-lock.json": LOCK_V3, "go/go.mod": "module x\n",
               "py/requirements.txt": "flask==3.0.2\nrequests\n", "node_modules/ignored/package-lock.json": LOCK_V3})
    r = sc.scan_workspace(ws, src)
    lock = next(f for f in r["lockfiles"] if f["path"] == "package-lock.json")
    assert lock["sha256"] == hashlib.sha256(LOCK_V3.encode()).hexdigest() and lock["committed"] is False
    assert r["unlocked"] == ["go/go.mod"] and r["unpinned"] == ["py/requirements.txt: requests"]
    assert not any("node_modules" in f["path"] for f in r["lockfiles"])
    text = " | ".join(r["warnings"])
    assert "go/go.mod has no lockfile" in text and "package-lock.json was generated by the build" in text
    assert "unpinned dependency: py/requirements.txt: requests" in text
    # a committed lockfile is clean
    _tree(src, {"package-lock.json": LOCK_V3})
    assert not any("generated by the build" in w for w in sc.scan_workspace(ws, src)["warnings"])


def test_corrupt_lockfile_is_reported_not_raised(tmp_path):
    _tree(tmp_path, {"package.json": "{}", "package-lock.json": "{not json"})
    r = sc.scan_workspace(tmp_path)
    assert r["errors"] and r["lockfiles"][0]["components"] == 0


@pytest.fixture
def proj(tmp_path, tmp_path_factory):
    return approved_project(tmp_path, tmp_path_factory)


def test_build_records_supply_chain_and_cutover_warns(proj, monkeypatch):
    fd = FakeDocker()
    monkeypatch.setattr(p2exec, "get_backend", lambda project=None: fd.backend(project))
    H.import_source(proj, from_original=True)
    real = H._copy_workspace

    def copy_and_lock(src, dst):                         # the fake build generates a lockfile in the workspace
        real(src, dst)
        (Path(dst) / "package-lock.json").write_text(LOCK_V3)
    monkeypatch.setattr(H, "_copy_workspace", copy_and_lock)
    ent = H.build(proj, "legacy")
    s = ent["supply_chain"]
    assert s["components"] == 3 and s["uncommitted"] == ["package-lock.json"] and s["lockfiles"][0]["sha256"]
    run = proj.root / "runs" / ent["build_run"]
    assert json.loads((run / "sbom.cdx.json").read_text())["bomFormat"] == "CycloneDX"
    rep = json.loads((run / "supply_chain.json").read_text())
    assert rep["components"] == 3 and "package-lock.json" in " ".join(rep["warnings"])
    assert json.loads((proj.root / "harness" / "state.json").read_text())["legacy"]["supply_chain"]["components"] == 3
    assert any("legacy build" in w and "generated by the build" in w for w in cutover._supply_chain_warnings(proj))
