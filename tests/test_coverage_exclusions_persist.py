"""Pre-M0 fix 1: gap-fill exclusions are persisted by analyze and used by every coverage consumer."""
import json

import pytest

from migration_agent.analyze.coverage import exclusions_path, load_exclusions, save_exclusions
from migration_agent.analyze.runner import run_analyze
from migration_agent.graph import load_latest
from migration_agent.llm.base import LLMResponse
from migration_agent.llm.offline import OfflineLLM
from migration_agent.pipeline import Inventory, InventoryItem
from migration_agent.review.approval import approve, readiness
from migration_agent.review.docrender import render_latest, write_latest
from migration_agent.verify.models import MigrationContract

from phase1_helpers import make_project

EXTRA = "INV-route-zzz"


@pytest.fixture()
def proj(tmp_path, tmp_path_factory):
    return make_project(tmp_path, tmp_path_factory)


def _add_item(p):
    inv = Inventory.model_validate_json(p.inventory_path.read_text())
    inv.items.append(InventoryItem(id=EXTRA, kind="route", name="GET /zzz"))
    p.inventory_path.write_text(inv.model_dump_json())


class ExcludingLLM(OfflineLLM):
    """OfflineLLM that classifies every gap-fill item as excluded."""

    def complete(self, *, task, system, prompt, json_mode=True, prompt_version="v1"):
        if task == "gap_fill":
            text = json.dumps({"action": "classify", "status": "excluded", "reason": "generated by the build"})
            return LLMResponse(text=text, model="offline")
        return super().complete(task=task, system=system, prompt=prompt, json_mode=json_mode,
                                prompt_version=prompt_version)


def test_analyze_persists_exclusions_and_offline_render_matches(proj):
    _add_item(proj)
    out = run_analyze(proj, ExcludingLLM())
    assert out["coverage_complete"] and out["unmapped"] == 0
    g = load_latest(proj.graph_dir)
    data = json.loads(exclusions_path(proj).read_text())
    assert data["graph_version"] == g.version
    assert load_exclusions(proj) == {EXTRA: "generated by the build"}
    doc = (proj.docs / "understanding.latest.md").read_text()
    assert render_latest(proj, g) == doc            # offline render == analyze render
    r = readiness(proj)
    assert not any("coverage incomplete" in b for b in r.blockers)
    assert not any("out of date" in b for b in r.blockers)
    approve(proj, "alice")
    c = MigrationContract.model_validate_json((proj.docs / "migration_contract.json").read_text())
    assert c.coverage.complete and c.coverage.excluded == 1 and c.coverage.unmapped == 0


def test_analyze_without_gap_fill_writes_empty_exclusions(proj):
    run_analyze(proj, OfflineLLM())
    assert exclusions_path(proj).exists() and load_exclusions(proj) == {}


def test_excluded_item_is_not_a_readiness_blocker(proj):
    _add_item(proj)
    write_latest(proj)
    assert any("coverage incomplete" in b and EXTRA in b for b in readiness(proj).blockers)
    save_exclusions(proj, {EXTRA: "vendored"})
    write_latest(proj)
    r = readiness(proj)
    assert r.ready, r.blockers


def test_corrupt_exclusions_file_is_a_blocker(proj):
    exclusions_path(proj).write_text("{not json")
    r = readiness(proj)
    assert any("coverage_exclusions.json unreadable" in b for b in r.blockers)
